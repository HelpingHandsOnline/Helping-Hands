      <h1>Privacy Policy</h1>
      <p class="legal-updated">Last updated: 1 August 2026</p>
      <p>Helping Hands Community Assist ("we", "us") respects your privacy. This policy explains what information we collect when you use this platform, why we collect it, and how it's protected.</p>

      <h2 id="collect">1. Information We Collect</h2>
      <p>When you create an account, we collect your first name, last name, email address, phone number, and the role you select (requester, volunteer, or both). When you submit a help request, we collect the category of help needed, your location or address, preferred date and time, and any notes you add. When you message us through the Contact Us form, we collect your name, email, and message content.</p>

      <h2 id="use">2. How We Use It</h2>
      <p>We use your information to match requests with available volunteers, to let you log back into your account, to notify you about the status of a request or task, and to respond to enquiries sent through the contact form. We do not sell your information to third parties, and we do not use it for advertising.</p>

      <h2 id="share">3. Sharing With Volunteers</h2>
      <p>Your contact details and address are kept private until a volunteer formally accepts your request. Once a match is made, only the minimum contact information needed to complete the task is shared between the requester and the volunteer.</p>

      <h2 id="storage">4. Storage &amp; Security</h2>
      <p>Account passwords are never stored in plain text. Depending on which version of this site you are using, information is stored either securely in your browser (for demonstration purposes) or in a password-hashed server database. We recommend using a unique password for this platform and not sharing your login details with anyone.</p>

      <h2 id="rights">5. Your Rights</h2>
      <p>You can request a copy of the information we hold about you, ask us to correct inaccurate details, or ask us to delete your account entirely. To do any of these, contact us using the details below and we'll respond within a reasonable time.</p>

      <h2 id="cookies">6. Cookies</h2>
      <p>This site uses only the storage necessary to keep you logged in and remember your preferences (such as your selected help category while filling out a form). We do not use third-party advertising or tracking cookies.</p>

      <h2 id="children">7. Children's Privacy</h2>
